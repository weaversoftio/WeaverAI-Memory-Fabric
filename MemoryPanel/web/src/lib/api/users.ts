/**
 * api/users.ts — User + UserKey + UserConfig (meta/user/* + meta/user-key/* + meta/config/user/*).
 */
import { metaPost, metaListAll, getCurrentUser, dedupeInFlight } from './base';
import type { PublicUser } from './types';

/** Kernel user/create response (CreateUserResult) -- contains no username, contains a one-time key */
export interface CreateUserResult {
  user_id: string;
  user_type: 'normal' | 'system_admin';
  created_at: string;
  /** Default API key in plaintext, returned only in this response */
  default_user_key: string;
}

export const usersApi = {
  /** List users with pagination; pass { username } for an exact match or { user_ids } to filter */
  list: (params?: { username?: string; user_ids?: string[] }) => metaListAll<PublicUser>('user/list', { ...params }),

  /** User details */
  get: (userId: string) => metaPost<PublicUser>('user/get', { user_id: userId }),

  /**
   * Create a user (transparently proxied to the backend user/create).
   *
   * The response is CreateUserResult: contains user_id / user_type / created_at / default_user_key.
   * default_user_key is a one-time plaintext key, returned only in this response.
   *
   * WARNING (permission): the current user must hold system_admin permission; ordinary users get 403.
   */
  create: (data: { username: string; auth_provider: string; external_id: string; display_name?: string; email?: string }) =>
    metaPost<CreateUserResult>('user/create', data),

  /**
   * Create a user and explicitly specify user_key (transparently proxied to the backend user/create-with-key).
   *
   * Sibling of user/create: all behavior matches create; the only difference is that default_user_key uses the caller-supplied user_key directly,
   * rather than being generated by the kernel. Suited to the scenario "when a panel admin creates an account, a known key must be pre-assigned for external distribution".
   * A user_key conflict makes the kernel return 409 `duplicate_user_key`, which the Panel backend passes through as is.
   *
   * WARNING (permission) same as create: the current user must hold system_admin permission; ordinary users get 403.
   */
  createWithKey: (data: {
    username: string;
    user_key: string;
    external_id?: string;
    auth_provider?: string;
    display_name?: string;
    email?: string;
  }) => metaPost<CreateUserResult>('user/create-with-key', data),

  /**
   * Delete a user (transparently proxied to the backend user/delete).
   *
   * WARNING (permission) same as above: requires system_admin to call.
   */
  delete: (userId: string) => metaPost<{ ok: boolean }>('user/delete', { user_id: userId }),
};

// ========================= User API Keys (meta/user-key/*) =========================
//
// Uses the standard meta action (same model as team/agent, dual-header auth).

export interface UserKey {
  key_id: string;
  user_id?: string;
  name?: string;
  /** Displayable prefix of the key (e.g. `sk-mem-ab12****`), returned by kernel list/get, used to identify which key it is without the secret */
  key_prefix?: string;
  /** Plaintext key -- appears only once in the creation response; the kernel never returns it afterwards (list/get), by security design */
  key_value?: string;
  created_at?: string;
  expires_at?: string;
  revoked_at?: string;
  last_used_at?: string;
}

export const userKeysApi = {
  /** List all API Keys of the currently logged-in user (fetches everything via kernel pagination) */
  list: () => dedupeInFlight('user-key/list', () => metaListAll<UserKey>('user-key/list', {})),

  /** Create a new Key; the plaintext key_value in the return value is shown only this once, and the caller must show it to the user immediately */
  create: (data: { name?: string; expires_at?: string; user_id?: string }) => metaPost<UserKey>('user-key/create', data),

  /** Revoke a Key */
  revoke: (keyId: string) => metaPost<{ ok: boolean }>('user-key/revoke', { key_id: keyId }),
};

// ========================= User Config (meta/config/user/*) =========================

export type AssetCapabilityKey = 'skill.enabled' | 'llm_wiki.enabled' | 'code_graph.enabled' | 'chat_memory.enabled';

export interface UserConfigItem {
  module: string;
  param_name: AssetCapabilityKey | string;
  param_key: string;
  description: string;
  effective_value: string;
}

export interface UserConfigView {
  user_id: string;
  module: string;
  module_description: string;
  items: UserConfigItem[];
}

export type AssetCapabilityConfig = Record<AssetCapabilityKey, boolean>;

const ASSET_CAPABILITY_KEYS: AssetCapabilityKey[] = [
  'skill.enabled',
  'llm_wiki.enabled',
  'code_graph.enabled',
  'chat_memory.enabled',
];

function boolFromConfigValue(value: string | undefined): boolean {
  return value === undefined ? true : value === '1' || value.toLowerCase() === 'true';
}

export const userConfigApi = {
  get: (userId: string, module: string, paramName?: string) =>
    metaPost<UserConfigView>('config/user/get', { user_id: userId, module, param_name: paramName }),

  set: (userId: string, module: string, params: Record<string, string>) =>
    metaPost<{ ok: boolean }>('config/user/set', { user_id: userId, module, params }),

  getAssetCapabilities: async (): Promise<AssetCapabilityConfig> => {
    const me = await getCurrentUser();
    const view = await userConfigApi.get(me.user_id, 'asset_type');
    const byName = new Map(view.items.map((it) => [it.param_name, it.effective_value]));
    return Object.fromEntries(
      ASSET_CAPABILITY_KEYS.map((key) => [key, boolFromConfigValue(byName.get(key))]),
    ) as AssetCapabilityConfig;
  },

  setAssetCapability: async (key: AssetCapabilityKey, enabled: boolean) => {
    const me = await getCurrentUser();
    return userConfigApi.set(me.user_id, 'asset_type', { [key]: enabled ? '1' : '0' });
  },
};
