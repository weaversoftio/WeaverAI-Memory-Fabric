/**
 * api/auth.ts - login liveness check + environment binding.
 *
 * Login flow:
 *   1. GET /meta/instances to pick an instance
 *   2. The user enters their own user_key (sk-mem-...)
 *   3. POST /meta/auth/verify (Header carries only X-Wamf-Service-Id, body carries user_key)
 *   4. data.valid === true -> login succeeds, the frontend writes { instance_id, user_key, user } into the session
 * No OAuth, no Cookie; see lib/panelSession.ts.
 */
import { request, metaCall } from './base';
import type { PublicUser } from './types';

export const authVerifyApi = {
  /** Login liveness check: the Header carries only the instance ID, user_key goes only in the body (meta-api.openapi.yaml section auth/verify) */
  verify: (instanceId: string, userKey: string) =>
    metaCall<{ valid: boolean; user?: PublicUser }>(
      'auth/verify',
      { user_key: userKey },
      { 'X-Wamf-Service-Id': instanceId }
    ),
};

export interface AuthMethod {
  id: string;
  type: 'user_key' | 'sso' | 'oidc';
  display_name: string;
  enabled: boolean;
}

/**
 * user_key login (compatible with user-held keys).
 *
 * Isomorphic to the two-step confirmation of the Enterprise SSO flow: first preview to see "whose key this is", then login to confirm.
 * When the system has no account for this key, login creates one with it (registration on first login).
 *
 * Goes through the Panel rather than the frontend connecting to core directly: creating an account needs instance admin credentials, which the frontend cannot get.
 */
export const userKeyLoginApi = {
  preview: (instanceId: string, userKey: string) =>
    request<{
      exists: boolean;
      user_id?: string;
      username?: string;
      display_name?: string;
      user_type?: string;
    }>('POST', '/api/v1/auth/user-key/preview', {
      instance_id: instanceId,
      user_key: userKey,
    }),
  login: (instanceId: string, userKey: string, username?: string) =>
    request<{
      authenticated: boolean;
      instance_id: string;
      user_id: string;
      user?: PublicUser;
      created: boolean;
    }>('POST', '/api/v1/auth/user-key/login', {
      instance_id: instanceId,
      user_key: userKey,
      username,
    }),
};

export const authMethodsApi = {
  list: () => request<{ methods: AuthMethod[] }>('GET', '/api/v1/auth/methods'),
  loginSso: (instanceId: string, returnTo = '/') => {
    const params = new URLSearchParams({ instance_id: instanceId, return_to: returnTo });
    window.location.assign(`/api/v1/auth/idp/sso/login?${params.toString()}`);
  },
  /** OIDC (e.g. Keycloak): full-page redirect to the IdP; it comes back to the panel signed in. */
  loginOidc: (providerId: string, instanceId: string, returnTo = '/') => {
    const params = new URLSearchParams({ instance_id: instanceId, return_to: returnTo });
    window.location.assign(`/api/v1/auth/idp/${encodeURIComponent(providerId)}/login?${params.toString()}`);
  },
  /** Ends the panel's IdP session and the IdP's own session, then lands back on the login page. */
  logoutIdp: () => {
    window.location.assign('/api/v1/auth/idp/logout');
  },
  session: (instanceId?: string) => {
    const query = instanceId ? `?instance_id=${encodeURIComponent(instanceId)}` : '';
    return request<{
      authenticated: boolean;
      method?: 'idp';
      instance_id?: string;
      user_id?: string;
      provider_id?: string;
      display_name?: string;
      user?: PublicUser;
      expires_at?: number;
      pending?: boolean;
      pending_identity?: {
        display_name?: string;
        login_name?: string;
        subject?: string;
        provider_id?: string;
        provider_type?: 'sso' | 'oidc';
      };
    }>('GET', `/api/v1/auth/session${query}`);
  },
  /**
   * Preview whether the user_key entered by the user already has a matching account in the system.
   * When exists=true it returns that account's info, for the user to confirm "bind to it" or "create new".
   */
  previewSsoKey: (userKey: string) =>
    request<{
      exists: boolean;
      user_id?: string;
      username?: string;
      display_name?: string;
      user_type?: string;
    }>('POST', '/api/v1/auth/idp/sso/preview-key', { user_key: userKey }),
  completeSso: (input: {
    username?: string;
    userKey?: string;
    customUserKey?: string;
    /** OIDC first login: create a new account with a generated key instead of linking one. */
    createNew?: boolean;
  }) =>
    request<{
      authenticated: boolean;
      instance_id: string;
      user_id: string;
      user?: PublicUser;
      user_key?: string;
      user_key_autogenerated?: boolean;
    }>(
      'POST',
      '/api/v1/auth/idp/sso/complete',
      {
        username: input.username,
        // Both fields must be passed: the backend completePendingSsoLogin reads
        // `input.userKey || input.customUserKey`. Previously only custom_user_key was sent,
        // while the caller (LoginGate) passes userKey -> the backend received an empty key ->
        // 400 INVALID_USER_KEY, and the account creation request could never be sent.
        user_key: input.userKey,
        custom_user_key: input.customUserKey,
        create_new: input.createNew,
      },
    ),
  /**
   * Abandon the Enterprise SSO pending-confirmation login and switch to user_key login.
   *
   * The backend clears the pending Cookie and issues a suppression flag: the gateway injects Enterprise SSO identity headers on every request,
   * and clearing only pending would immediately bounce a refreshed page back to the Enterprise SSO confirmation page.
   */
  dismissSso: () => request<{ ok: boolean }>('POST', '/api/v1/auth/idp/sso/dismiss'),

  /**
   * Undo dismiss and switch back to Enterprise SSO login (clear the suppression flag).
   *
   * Paired with dismissSso: called when the user clicks "Switch to Enterprise SSO login" on the user_key page,
   * otherwise the earlier suppression flag would let Enterprise SSO ingress pass straight through, staying on the user_key form.
   */
  resumeSso: () => request<{ ok: boolean }>('POST', '/api/v1/auth/idp/sso/resume'),
};

// ========================= Environment Bindings =========================
//
// WARNING: the current deployment has not registered the /api/v1/users/* routes, so the following endpoints may 404.
// The code is kept for environments that still enable these routes; if a page depends on this group of endpoints, first confirm the routes are registered.

/**
 * Environment binding (environment_bindings): links the user's external user_id in an external environment (IDE / coding assistant, etc.)
 * to the user on this platform, so the proxy can look up the team / agent / task
 * via (environment, environment_user_id).
 *
 * Uniqueness constraint: (environment, environment_user_id) is globally unique; occupied by someone else -> 409.
 */
export interface EnvironmentBinding {
  id: string;
  user_id: string;
  environment: string;
  environment_user_id: string;
  created_at: string;
  updated_at: string;
}

export const environmentBindingsApi = {
  /** List all bindings of the current logged-in user */
  list: () => request<EnvironmentBinding[]>('GET', '/api/v1/users/me/environment-bindings'),

  /** Add a binding (idempotent: repeating POST of the same (env, env_user_id) for the same user does not error) */
  create: (data: { environment: string; environment_user_id: string }) =>
    request<EnvironmentBinding>('POST', '/api/v1/users/me/environment-bindings', data),

  /** Delete a binding (can only delete your own; deleting someone else's -> 403) */
  remove: (id: string) => request<{ ok: boolean }>('DELETE', `/api/v1/users/me/environment-bindings/${id}`),
};
