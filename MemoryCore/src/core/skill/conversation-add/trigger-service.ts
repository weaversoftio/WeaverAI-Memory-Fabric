/**
 * SkillTriggerService — archive segment (§7.4).
 *
 * Called after the Handler main flow decides "archiving is needed"; completes "**write the archive first,
 * then register the task**" in the following order:
 *   ① generate archive_key / task_id / archived_at_ms
 *   ② write the archive file (already exists = treated as success; if this step is slow or fails there is no orphan task)
 *   ③ acquire tasks-mutex → read `_tasks.json` → append the task → write back → enqueue to Redis inside the same critical section
 *
 * Order change history:
 *   2026-07-20 - the original order was ①→②(write _tasks.json + enqueue inside tasksMutex)→③(write archive),
 *   which triggered in the test environment: writeArchive was slower than the worker's BRPOP (a single put took ~10s because of slow storage I/O (self-signed TLS + intranet
 *   DNS jitter), the worker got in first, readArchive returned null, judged it a ghost and silently dropped
 *   a real task. After changing to "archive first, then task": a slow/failed archive errors out
 *   in place on the handler side, the worker never sees a task without an archive, and on the happy path no ghost is misjudged.
 *
 * Failure states under the new order:
 *   - writeArchive throws → the handler gets the exception, _tasks.json has no leftovers and Redis has no agent;
 *     the Client simply retries the whole thing (archive is idempotent: the same archived_at_ms is skipped, not overwritten).
 *   - writeArchive succeeds → either writeTasks / enqueueAgent failing inside the mutex → only leaves an
 *     "orphan archive" (a jsonl of 4 to several tens of KB, invisible to the worker, cleaned by the storage lifecycle
 *     or later GC). This is far better than before: no risk of losing a task.
 */

import { randomUUID } from "node:crypto";

import type {
  AgentTuple,
  ISkillAgentTaskQueue,
} from "./agent-task-queue.js";
import type {
  BufferedMessages,
  SessionKey,
  SkillBufferStorage,
  SkillTaskEntry,
} from "./buffer-storage.js";
import { obsLogger } from "../../report/obs-logger.js";

export interface TriggerArchiveInput {
  session: SessionKey;
  bufferAtTrigger: BufferedMessages;
  /** Business-side task reference (pass-through field), optional. */
  taskRefId?: string;
  /**
   * Exclusive to direct-trigger (`/v3/skill/extract`): the main Agent's extraction hint,
   * landed into SkillTaskEntry.reason and passed through to extractor.extract when the Worker consumes it.
   * Not passed by the conversation/add path.
   */
  reason?: string;
  /**
   * Exclusive to direct-trigger: the extractor LLM iteration cap, landed into SkillTaskEntry.max_iterations.
   * Not passed by the conversation/add path (uses the extractor-side default).
   */
  maxIterations?: number;
  /**
   * The request_id generated by the upstream handler. When passed, the trigger's internal segmented obsLogger events
   * carry it, making it easy to filter the full handler + trigger + worker chain by req_id. Omitting it does not affect functionality.
   */
  perfRequestId?: string;
}

export interface TriggerArchiveResult {
  taskId: string;
  archivedAtMs: number;
  archiveKey: string;
}

export interface SkillTriggerServiceOptions {
  buffer: SkillBufferStorage;
  queue: ISkillAgentTaskQueue;
  /**
   * tasks-mutex lock TTL, default 10000ms. **The lock's own expiry** - only a safeguard so
   * it auto-releases after the lock-holding process crashes. The real critical section should be far smaller than this value (a storage read-modify-write is usually <300ms).
   */
  tasksMutexLockTtlMs?: number;
  /**
   * Max wait time for contending for the tasks-mutex, default 30000ms (30s).
   * When many sessions archive for the same agent concurrently (entering the critical section together), queueing time accumulates,
   * and waitDeadline must be >> single critical-section duration × expected queue length.
   */
  tasksMutexWaitDeadlineMs?: number;
  /** Time source, for test injection. */
  now?: () => number;
}

export class SkillTriggerService {
  private readonly buffer: SkillBufferStorage;
  private readonly queue: ISkillAgentTaskQueue;
  private readonly tasksMutexLockTtlMs: number;
  private readonly tasksMutexWaitDeadlineMs: number;
  private readonly now: () => number;

  constructor(opts: SkillTriggerServiceOptions) {
    this.buffer = opts.buffer;
    this.queue = opts.queue;
    this.tasksMutexLockTtlMs = opts.tasksMutexLockTtlMs ?? 10_000;
    this.tasksMutexWaitDeadlineMs = opts.tasksMutexWaitDeadlineMs ?? 30_000;
    this.now = opts.now ?? (() => Date.now());
  }

  /**
   * Trigger one archive. Executes §7.4 ①→②→③→④.
   * On failure it throws, so the Handler converts it to a 500 for the Client to retry.
   */
  async archive(input: TriggerArchiveInput): Promise<TriggerArchiveResult> {
    const { session, bufferAtTrigger, taskRefId } = input;

    // ① Generate identifiers
    const archivedAtMs = this.now();
    const archiveKey = this.buffer.archiveKey(session, archivedAtMs);
    // The prefix `skill-extract-task-` is an internal anchor (clearly distinguished from the business-side task_id).
    // One archive = one SkillTaskEntry.task_id; the handler-side `[skill-perf] phase=trigger.enqueueAgent
    // task_id=…` and the worker-side `[skill-perf] kind=worker phase=consume.*` share the same
    // value, so one grep pulls the full handler + worker timing. Old data with the `task-` prefix will be
    // consumed by the worker naturally, with no migration risk (filter compares task_id values for equality, without parsing the prefix).
    const taskId = `skill-extract-task-${randomUUID().slice(0, 8)}`;
    const agent: AgentTuple = {
      // 2026-07-30 instance_id goes into the tuple; after dequeuing from the queue the worker pool routes by it
      // to the matching instance's resources. If missing or empty it throws immediately.
      instance_id: session.instance_id,
      space_id: session.space_id,
      user_id: session.user_id,
      team_id: session.team_id,
      agent_id: session.agent_id,
    };

    const entry: SkillTaskEntry = {
      task_id: taskId,
      session_id: session.session_id,
      user_id: session.user_id,
      team_id: session.team_id,
      agent_id: session.agent_id,
      space_id: session.space_id,
      task_ref_id: taskRefId,
      archive_key: archiveKey,
      archived_at_ms: archivedAtMs,
      enqueued_at_ms: archivedAtMs,
      reason: input.reason,
      max_iterations: input.maxIterations,
    };

    // [obs] five key IOs of the archive segment: writeArchive / mutex acquire / readTasks /
    // writeTasks / enqueueAgent. In a past incident a writeArchive 10s slow took down the
    // worker-side empty check logic; here each segment gets structured events, with fields correlated by req_id / task_id.
    // obsLogger has internal try/catch + backend degradation, so no extra defense is needed.
    const rid = input.perfRequestId;
    const instanceId = session.instance_id;

    // ② Write the archive first (already exists is treated as success)
    //
    // Rationale for the order here: on the worker side, readArchive returning null is judged a ghost and the
    // corresponding task is deleted; if the archive segment came later than the task segment, any storage jitter (slow self-signed TLS handshake,
    // intranet DNS re-resolution, etc.) would open a window where "the task is registered but the archive has not landed yet",
    // and a worker BRPOP landing in that window would drop a real task as a ghost (2026-07-20 production
    // incident: writeArchive took 10s, two cores shared the work, and the other one dropped
    // the task at 5s). After changing to archive first and then task: a writeArchive error/slowness never
    // creates an orphan task; the worker only ever sees a task when its archive already exists.
    //
    // Failure state: writeArchive throws → throw straight to the handler, no leftovers.
    const t0Arch = Date.now();
    await this.buffer.writeArchive(session, archivedAtMs, bufferAtTrigger);
    obsLogger.info("skill.trigger.write_archive", {
      req_id: rid, task_id: taskId, instance_id: instanceId,
      dur_ms: Date.now() - t0Arch,
      archive_key: archiveKey,
    });

    // ③ Acquire the mutex → CAS-append the task to the tail → enqueue inside the same lock
    //
    // Key guarantee (root cause of ghost tasks): writeTasks and enqueueAgent must be done inside the same
    // tasks-mutex critical section, otherwise a race window opens against the Worker side's "empty check → removeAgent":
    // before the Worker calls removeAgent outside the mutex, this function's
    // enqueueAgent may skip the LPUSH because the Set still holds the old agent (SADD returns 0),
    // leaving the new task landed in _tasks.json while the Redis queue has no record of
    // that agent - the task is stuck forever, and no later mechanism will re-trigger it.
    // Folding enqueueAgent into the same lock, together with the Worker-side fix (see extract-worker.ts),
    // guarantees "write task + enqueue" and "empty check + dequeue" are mutually exclusive and never interleave.
    const t0MutexEntry = Date.now();
    await this.queue.withTasksMutex(
      agent,
      { lockTtlMs: this.tasksMutexLockTtlMs, waitDeadlineMs: this.tasksMutexWaitDeadlineMs },
      async () => {
        const mutexAcquiredAt = Date.now();
        obsLogger.info("skill.trigger.mutex_acquire", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: mutexAcquiredAt - t0MutexEntry,
        });

        const t0Read = Date.now();
        const doc = await this.buffer.readTasks(agent);
        obsLogger.info("skill.trigger.read_tasks", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Read,
          existing_tasks: doc.tasks.length,
        });

        doc.tasks.push(entry);
        doc.updated_at_ms = archivedAtMs;

        const t0Write = Date.now();
        await this.buffer.writeTasks(agent, doc);
        obsLogger.info("skill.trigger.write_tasks", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Write,
          total_tasks: doc.tasks.length,
        });

        const t0Enq = Date.now();
        const enqueued = await this.queue.enqueueAgent(agent);
        obsLogger.info("skill.trigger.enqueue_agent", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Enq,
          added: enqueued,
        });
      },
    );
    obsLogger.info("skill.trigger.mutex_total", {
      req_id: rid, task_id: taskId, instance_id: instanceId,
      dur_ms: Date.now() - t0MutexEntry,
    });

    return { taskId, archivedAtMs, archiveKey };
  }
}
